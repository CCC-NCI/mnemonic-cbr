def to_serializable(sample_rows: List[Dict[str, Any]],
                    per_stratum: int, seed: int,
                    notes: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Assemble the manifest dict. Field order is fixed so the JSON
    serialisation is deterministic.
    """
    rounded = []
    for s in sample_rows:
        rounded.append({
            "blind_id":     s["blind_id"],
            "case_id":      s["case_id"],
            "persona":      s["persona"],
            "architecture": s["architecture"],
            "student_leg":  s["student_leg"],
            "r5_band":      s["r5_band"],
            "llm_R5":       s.get("R5"),
            "llm_R2":       s.get("R2"),
            "file_path":    s["file_path"],
        })
    return {
        "version":          "1.0",
        "purpose":          "Human rater validation sampling frame",
        "sampling_seed":    seed,
        "per_stratum":      per_stratum,
        "n":                len(rounded),
        "strata":           f"{len(ARCHITECTURES)} architectures x 3 R5 bands = 15 strata",
        "band_definition":  {k: list(v) for k, v in R5_BANDS_PRIMARY.items()},
        "fallback_rule":    "tercile substitution within architecture on band underflow",
        "fallback_notes":   notes,
        "items":            rounded,
    }


def write_manifest(out_dir: Path, manifest: Dict[str, Any]) -> Tuple[Path, str]:
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "sampling_frame_manifest.json"
    payload = json.dumps(manifest, indent=2, sort_keys=False)
    json_path.write_text(payload)
    digest = hashlib.sha256(payload.encode("utf-8")).hexdigest()
    (out_dir / "sampling_frame_manifest.sha256.txt").write_text(digest + "\n")
    return json_path, digest


def write_summary_md(out_dir: Path, manifest: Dict[str, Any],
                     digest: str) -> Path:
    lines = []
    lines.append("# Sampling Frame Summary")
    lines.append("")
    lines.append(f"- n: {manifest['n']}")
    lines.append(f"- per stratum target: {manifest['per_stratum']}")
    lines.append(f"- seed: {manifest['sampling_seed']}")
    lines.append(f"- band definition: {manifest['band_definition']}")
    lines.append(f"- SHA 256: `{digest}`")
    lines.append("")
    lines.append("## Per stratum counts")
    lines.append("")
    counts: Dict[Tuple[str, str], int] = defaultdict(int)
    persona_counts: Dict[str, int] = defaultdict(int)
    leg_counts: Dict[str, int] = defaultdict(int)
    for item in manifest["items"]:
        counts[(item["architecture"], item["r5_band"])] += 1
        persona_counts[item["persona"]] += 1
        leg_counts[item["student_leg"]] += 1
    lines.append("| Architecture | low | mid | high | total |")
    lines.append("|--------------|----:|----:|-----:|------:|")
    for arch in ARCHITECTURES:
        row = [counts.get((arch, b), 0) for b in ("low", "mid", "high")]
        lines.append(
            f"| {arch} | {row[0]} | {row[1]} | {row[2]} | {sum(row)} |"
        )
    lines.append("")
    lines.append("## Persona balance")
    lines.append("")
    lines.append("| Persona | n |")
    lines.append("|---------|--:|")
    for p in PERSONAS:
        lines.append(f"| {p} | {persona_counts.get(p, 0)} |")
    lines.append("")
    lines.append("## Student leg balance")
    lines.append("")
    lines.append("| Leg | n |")
    lines.append("|-----|--:|")
    for leg in LEGS:
        lines.append(f"| {leg} | {leg_counts.get(leg, 0)} |")
    lines.append("")
    if manifest.get("fallback_notes"):
        lines.append("## Tercile fallback substitutions")
        lines.append("")
        for note in manifest["fallback_notes"]:
            lines.append(f"- `{note['architecture']} / {note['band']}`: {note['note']} "
                         f"(primary available {note['primary_available']}, "
                         f"tercile top up available {note['tercile_topup_available']}, "
                         f"final picked {note['final_picked']}).")
        lines.append("")
    else:
        lines.append("## Tercile fallback substitutions")
        lines.append("")
        lines.append("None. Every (architecture, R5 band) stratum had at least the per stratum target available under the primary band definition.")
        lines.append("")
    md_path = out_dir / "sampling_frame_summary.md"
    md_path.write_text("\n".join(lines))
    return md_path


# ---------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------

def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--manifest",
        type=Path,
        default=Path("results/phaseB_smoke_5turn/manifest.sqlite"),
        help="Path to the Phase D SQLite manifest (default %(default)s).",
    )
    p.add_argument(
        "--dialogues-dir",
        type=Path,
        default=Path("results/phaseB_smoke_5turn/dialogues"),
        help="Path to the Phase D dialogue JSON directory.",
    )
    p.add_argument(
        "--out",
        type=Path,
        required=True,
        help="Output directory.",
    )
    p.add_argument(
        "--per-stratum",
        type=int,
        default=10,
        help="Per stratum target (default %(default)s).",
    )
    p.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed (default %(default)s).",
    )
    return p.parse_args()


def main() -> int:
    args = parse_args()
    rows = load_phase_d_rows(args.manifest)
    logger.info("Loaded %d Phase D dialogues from %s", len(rows), args.manifest)
    samples, notes = sample(rows, per_stratum=args.per_stratum, seed=args.seed)
    manifest = to_serializable(samples, per_stratum=args.per_stratum,
                               seed=args.seed, notes=notes)
    json_path, digest = write_manifest(args.out, manifest)
    md_path = write_summary_md(args.out, manifest, digest)
    logger.info("Wrote manifest: %s", json_path)
    logger.info("Wrote summary:  %s", md_path)
    logger.info("SHA 256 digest: %s", digest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
