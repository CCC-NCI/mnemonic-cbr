"""Sampling frame for the human rater validation study.

Action plan reference: VALIDATION_STUDY_ACTION_PLAN.md §0.5.

The script produces the frozen sampling manifest for the Prolific
rating round. It draws a stratified subset of the Phase D dialogues
under a fixed random seed, hashes the result, and writes both the
manifest and its SHA-256 digest to disk so the rated sample is
fixed in advance of any rater contact and reproducible from a
single command.

Stratification

  Primary strata: architecture (5 levels) × LLM judge R5 band
  (3 levels: low R5 in {1,2}, mid R5 = 3, high R5 in {4,5}).
  Yields 15 strata.

  Within each stratum: balance persona (5 levels) and student leg
  (2 levels) so that no persona or leg is structurally
  underrepresented. Within the persona x leg balance, draw without
  replacement under the fixed seed.

  Fallback rule (band underflow): if any (architecture, R5 band)
  stratum contains fewer dialogues than the per stratum target,
  the script switches to terciles of the observed R5 distribution
  within that architecture, takes as many as available, and writes
  the substitution to the manifest's `notes` field. The rule is
  registered in §0.5 of the action plan.

  Default per stratum target: 10 (yields n = 150 across 15 strata).
  Adjustable via --per-stratum.

Inputs

  --manifest         path to the Phase D SQLite manifest.
  --dialogues-dir    path to the Phase D dialogue JSON directory.
  --out              output directory.
  --per-stratum      per stratum target (default 10).
  --seed             random seed (default 42).

Outputs (under --out)

  sampling_frame_manifest.json        list of sampled dialogue IDs
                                      with full strata labels and
                                      rationale notes.
  sampling_frame_manifest.sha256.txt  SHA 256 digest of the manifest
                                      JSON (string of 64 hex chars).
  sampling_frame_summary.md           human readable summary table
                                      of per stratum counts plus any
                                      fallback substitutions.

Reproducibility contract

  Given the same --manifest, --dialogues-dir, --per-stratum, and
  --seed, two invocations produce byte identical
  sampling_frame_manifest.json files and identical SHA 256 digests.
  This is what the OSF deposit attests: that the rated subset was
  fixed before any rater contact and can be regenerated by a
  reviewer running this script with the same inputs.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import logging
import random
import sqlite3
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


logger = logging.getLogger("sample_validation_subset")
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s  %(levelname)-7s  %(name)s  %(message)s",
)


# ---------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------

ARCHITECTURES = ("baseline", "hybrid", "pure_ai", "pure_cbr_llm", "pure_cbr_tpl")
PERSONAS = ("traditional", "socratic", "constructive", "experiential", "rule_based")
LEGS = ("leg_a", "leg_b")

# Primary R5 band definition. Each band is a tuple of R5 values that
# count as that band. low covers struggle (R5 1 or 2), mid is the
# transition (R5 = 3), high is clear progress (R5 4 or 5).
R5_BANDS_PRIMARY = {
    "low":  (1, 2),
    "mid":  (3,),
    "high": (4, 5),
}


# ---------------------------------------------------------------------
# Data classes (simple dicts; explicit fields for clarity)
# ---------------------------------------------------------------------

def make_blind_id(case_id: str, persona: str, architecture: str,
                  student_leg: str, idx: int) -> str:
    """Stable opaque ID for one sampled dialogue. The blind ID hides
    architecture and persona from the rater while staying
    deterministic given the sampling state.
    """
    payload = f"{case_id}|{persona}|{architecture}|{student_leg}|{idx}"
    h = hashlib.sha256(payload.encode("utf-8")).hexdigest()
    return "D" + h[:10]


# ---------------------------------------------------------------------
# Stratified sampling
# ---------------------------------------------------------------------

def load_phase_d_rows(manifest_db: Path) -> List[Dict[str, Any]]:
    """Read every dialogue row from the Phase D SQLite manifest.

    Returns a list of dicts, one per dialogue, with the columns the
    sampling logic needs.
    """
    if not manifest_db.exists():
        raise FileNotFoundError(
            f"Phase D manifest not found at {manifest_db}"
        )
    conn = sqlite3.connect(str(manifest_db))
    conn.row_factory = sqlite3.Row
    rows = []
    for r in conn.execute(
        "select case_id, persona, architecture, student_leg, "
        "       R1, R2, R3, R4, R5, R6, "
        "       file_path "
        "from dialogues "
        "order by case_id, persona, architecture, student_leg"
    ):
        rows.append(dict(r))
    conn.close()
    return rows


def assign_r5_band_primary(r5: Optional[int]) -> Optional[str]:
    if r5 is None:
        return None
    for band, values in R5_BANDS_PRIMARY.items():
        if r5 in values:
            return band
    return None


def assign_r5_band_terciles(r5_values: List[int]) -> Dict[int, str]:
    """Fallback band assignment by terciles of the observed R5
    distribution. Returns a dict from each observed R5 value to the
    tercile label low / mid / high.
    """
    sorted_vals = sorted(r5_values)
    n = len(sorted_vals)
    third = max(1, n // 3)
    cuts = [sorted_vals[third - 1], sorted_vals[min(n - 1, 2 * third - 1)]]
    out = {}
    for v in set(sorted_vals):
        if v <= cuts[0]:
            out[v] = "low"
        elif v <= cuts[1]:
            out[v] = "mid"
        else:
            out[v] = "high"
    return out


def stratify_rows(rows: List[Dict[str, Any]]) -> Dict[Tuple[str, str], List[Dict[str, Any]]]:
    """Bucket rows by (architecture, R5 band) using the primary band
    definition (R5_BANDS_PRIMARY). Rows with R5 outside 1 to 5
    (parse failure) are dropped from the sampling pool.
    """
    buckets: Dict[Tuple[str, str], List[Dict[str, Any]]] = defaultdict(list)
    for r in rows:
        band = assign_r5_band_primary(r.get("R5"))
        if band is None:
            continue
        arch = r["architecture"]
        buckets[(arch, band)].append(r)
    return buckets


def balanced_pick(rows: List[Dict[str, Any]], target: int,
                  rng: random.Random) -> List[Dict[str, Any]]:
    """Pick up to `target` rows from a single stratum, balancing
    persona and leg. Algorithm: shuffle once under the rng, then
    pick by interleaving across (persona, leg) cells so no persona
    or leg dominates the stratum.
    """
    if target <= 0 or not rows:
        return []
    # Group by (persona, leg) cell.
    by_cell: Dict[Tuple[str, str], List[Dict[str, Any]]] = defaultdict(list)
    for r in rows:
        by_cell[(r["persona"], r["student_leg"])].append(r)
    # Stable shuffle within each cell under the rng.
    for cell in by_cell.values():
        rng.shuffle(cell)
    # Round robin through cells in a deterministic order until target
    # is met or we run out of rows.
    cell_keys = sorted(by_cell.keys())
    rng.shuffle(cell_keys)
    out: List[Dict[str, Any]] = []
    while len(out) < target and any(by_cell.values()):
        progress = False
        for key in cell_keys:
            if not by_cell[key]:
                continue
            out.append(by_cell[key].pop(0))
            progress = True
            if len(out) >= target:
                break
        if not progress:
            break
    return out


def sample(rows: List[Dict[str, Any]], per_stratum: int,
           seed: int) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """Run the stratified sample.

    Returns
    -------
    samples: list of sampled rows with extra fields band, blind_id.
    notes:   list of substitution / fallback records, one per
             affected stratum.
    """
    rng = random.Random(seed)
    notes: List[Dict[str, Any]] = []
    buckets = stratify_rows(rows)
    samples: List[Dict[str, Any]] = []
    sample_idx = 0
    for arch in ARCHITECTURES:
        for band in ("low", "mid", "high"):
            pool = buckets.get((arch, band), [])
            available = len(pool)
            if available >= per_stratum:
                picked = balanced_pick(pool, per_stratum, rng)
                effective_band = band
                note_record = None
            else:
                # Fallback: take everything we have at the primary
                # band, then top up from terciles of the architecture's
                # observed R5 distribution.
                arch_pool = [r for r in rows if r["architecture"] == arch
                             and r.get("R5") in (1, 2, 3, 4, 5)]
                arch_r5 = [r["R5"] for r in arch_pool]
                tercile_map = assign_r5_band_terciles(arch_r5)
                tercile_pool = [r for r in arch_pool
                                if tercile_map.get(r["R5"]) == band]
                already_ids = {r["file_path"] for r in pool}
                extras = [r for r in tercile_pool
                          if r["file_path"] not in already_ids]
                rng.shuffle(extras)
                topped = list(pool) + extras
                picked = balanced_pick(topped, per_stratum, rng)
                effective_band = band
                note_record = {
                    "architecture": arch,
                    "band": band,
                    "primary_available": available,
                    "tercile_topup_available": len(extras),
                    "final_picked": len(picked),
                    "note": (
                        "Primary R5 band underflowed at target "
                        f"{per_stratum}; supplemented from terciles of "
                        f"observed R5 distribution within architecture "
                        f"{arch}."
                    ),
                }
                notes.append(note_record)
                logger.warning(
                    "Stratum (%s, %s) underflowed (%d < %d). Tercile fallback applied; final picked %d.",
                    arch, band, available, per_stratum, len(picked),
                )
            for r in picked:
                sample_idx += 1
                r_copy = dict(r)
                r_copy["r5_band"] = effective_band
                r_copy["blind_id"] = make_blind_id(
                    r["case_id"], r["persona"], r["architecture"],
                    r["student_leg"], sample_idx,
                )
                samples.append(r_copy)
    return samples, notes


